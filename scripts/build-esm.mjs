/* Builds esm/: one ES module per component, for bundlers, React and Next.js.
 *
 * An engine is a script for a page: it reads window as it loads. A module
 * may be imported on a server, where there is no window. So each module
 * here holds its engine inside a function, word for word, and runs it the
 * first time one of its exports is called in a browser. Importing it does
 * nothing at all.
 *
 * The engines are never edited: change <name>/<name>.js, then run
 *   node scripts/build-esm.mjs
 * No dependency.
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'esm');
const SITE = 'https://movingparts.supply';

// name, the global its engine leaves on window, whether it plays with GSAP,
// and the functions of that global a module hands on beside mount.
const COMPONENTS = [
  { name: 'text-scramble', global: 'TextScramble', gsap: false, extra: ['play'] },
  { name: 'velocity-marquee', global: 'VelocityMarquee', gsap: true, extra: [] },
  { name: 'dot-repel', global: 'DotRepel', gsap: false, extra: ['freeze', 'unfreeze'] },
  { name: 'button-01', global: 'ButtonMotion', gsap: true, extra: ['refresh'] },
  { name: 'pixel-ribbon', global: 'PixelRibbon', gsap: false, extra: ['freeze', 'unfreeze'] },
];

const pascal = (name) => name.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());

/* The settings of a component, read from the DEFAULTS block of its engine:
   key, type of the default, and the label written beside it. */
function settings(engine, name) {
  const block = engine.match(/^ {2}var DEFAULTS = \{\n([\s\S]*?)\n {2}\};/m);
  if (!block) throw new Error(`${name}: no DEFAULTS block`);
  return block[1].split('\n').map((line) => {
    const m = line.match(/^\s*(\w+):\s*(.+?),\s*\/\/\s*(.+)$/);
    if (!m) throw new Error(`${name}: unread DEFAULTS line: ${line}`);
    const value = m[2].trim();
    const type = /^(true|false)$/.test(value) ? 'boolean' : /^-?[\d.]+$/.test(value) ? 'number' : 'string';
    return { key: m[1], value, type, label: m[3].trim() };
  });
}

function moduleSource(c, engine) {
  const lines = [];
  lines.push(`/* ${c.name}, as an ES module. Generated by scripts/build-esm.mjs from`);
  lines.push(`   ${c.name}/${c.name}.js: edit that file, never this one.`);
  lines.push(`   Moving parts, MIT licence. ${SITE}/components/${c.name}/?from=npm */`);
  if (c.gsap) lines.push("import { gsap } from 'gsap';");
  lines.push('');
  lines.push('let api = null;');
  lines.push('');
  lines.push('// The engine, word for word. It runs once, in a browser, on the first call.');
  lines.push('function engine() {');
  lines.push(engine.trimEnd());
  lines.push('}');
  lines.push('');
  lines.push('/* Runs the engine if the page does not have it yet and returns its');
  lines.push(`   global, window.${c.global}. Returns null where there is no window. */`);
  lines.push('export function load() {');
  lines.push('  if (api) return api;');
  lines.push("  if (typeof window === 'undefined' || typeof document === 'undefined') return null;");
  if (c.gsap) lines.push('  if (!window.gsap) window.gsap = gsap;');
  lines.push(`  if (!window.${c.global} || !window.${c.global}.mount) engine();`);
  lines.push(`  api = window.${c.global};`);
  lines.push('  return api;');
  lines.push('}');
  lines.push('');
  lines.push('/* Mounts the effect on one element and returns its instance. The engine');
  lines.push('   mounts every marked element by itself as it loads and keeps an');
  lines.push('   instance it already has, so settings handed here would be dropped:');
  lines.push('   an element mounted before them is taken down first. */');
  lines.push('export function mount(element, settings) {');
  lines.push('  const lib = load();');
  lines.push('  if (!lib || !element) return null;');
  lines.push('  if (settings) lib.destroy(element);');
  lines.push('  return lib.mount(element, settings);');
  lines.push('}');
  lines.push('');
  lines.push('export function destroy(element) {');
  lines.push('  if (api && element) api.destroy(element);');
  lines.push('}');
  lines.push('');
  lines.push('// Mounts every marked element inside root, the document by default.');
  lines.push('export function auto(root) {');
  lines.push('  const lib = load();');
  lines.push('  if (lib) lib.auto(root);');
  lines.push('}');
  for (const fn of c.extra) {
    lines.push('');
    lines.push(`export function ${fn}(element) {`);
    lines.push(`  if (api && element) api.${fn}(element);`);
    lines.push('}');
  }
  lines.push('');
  return lines.join('\n');
}

function typesSource(c, list) {
  const type = `${pascal(c.name)}Settings`;
  const lines = [];
  lines.push(`// ${c.name}. Generated by scripts/build-esm.mjs from the DEFAULTS of the engine.`);
  lines.push('');
  lines.push(`export interface ${type} {`);
  for (const s of list) {
    lines.push(`  /** ${s.label} Default: ${s.value}. */`);
    lines.push(`  ${s.key}?: ${s.type};`);
  }
  lines.push('}');
  lines.push('');
  lines.push('export interface Instance {');
  lines.push('  destroy(): void;');
  lines.push('  [key: string]: unknown;');
  lines.push('}');
  lines.push('');
  lines.push('export interface Library {');
  lines.push(`  mount(element: Element, settings?: ${type}): Instance | null;`);
  lines.push('  destroy(element: Element): void;');
  lines.push('  auto(root?: ParentNode): void;');
  lines.push(`  defaults: Required<${type}> | null;`);
  lines.push('  [key: string]: unknown;');
  lines.push('}');
  lines.push('');
  lines.push(`/** Runs the engine once and returns window.${c.global}, or null on a server. */`);
  lines.push('export function load(): Library | null;');
  lines.push('/** Mounts the effect on one element. Does nothing, and returns null, on a server. */');
  lines.push(`export function mount(element: Element | null, settings?: ${type}): Instance | null;`);
  lines.push('export function destroy(element: Element | null): void;');
  lines.push('/** Mounts every marked element inside root, the document by default. */');
  lines.push('export function auto(root?: ParentNode): void;');
  for (const fn of c.extra) lines.push(`export function ${fn}(element: Element | null): void;`);
  lines.push('');
  return lines.join('\n');
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

for (const c of COMPONENTS) {
  const engine = readFileSync(join(ROOT, c.name, `${c.name}.js`), 'utf8');
  if (!engine.includes(`global.${c.global} = `)) throw new Error(`${c.name}: the engine does not set window.${c.global}`);
  writeFileSync(join(OUT, `${c.name}.js`), moduleSource(c, engine));
  writeFileSync(join(OUT, `${c.name}.d.ts`), typesSource(c, settings(engine, c.name)));
  console.log(`esm/${c.name}.js, esm/${c.name}.d.ts`);
}

const index = [
  '/* The five free components of Moving parts. Each one is its own entry,',
  "   'movingparts-free/<name>', so a page only loads what it uses. This file",
  '   lists them and imports nothing. Generated by scripts/build-esm.mjs. */',
  'export const components = [',
  ...COMPONENTS.map((c) => `  { name: '${c.name}', global: '${c.global}', gsap: ${c.gsap}, page: '${SITE}/components/${c.name}/?from=npm' },`),
  '];',
  '',
].join('\n');
writeFileSync(join(OUT, 'index.js'), index);
writeFileSync(join(OUT, 'index.d.ts'), [
  'export interface FreeComponent {',
  '  name: string;',
  '  global: string;',
  '  gsap: boolean;',
  '  page: string;',
  '}',
  'export const components: FreeComponent[];',
  '',
].join('\n'));
console.log('esm/index.js, esm/index.d.ts');
